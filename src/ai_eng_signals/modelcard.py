"""Write models/topic-classifier/MODEL_CARD.md from reports/topic-eval.json."""

from __future__ import annotations

import json

from . import ROOT
from .posts import EVAL, TOPICS

CARD = ROOT / "models" / "topic-classifier" / "MODEL_CARD.md"


def _row(name: str, m: dict) -> str:
    return f"| {name} | {m['accuracy']:.0%} | {m['macro_f1']:.2f} |"


def render(report: dict) -> str:
    base, llm = report["baseline"], report.get("llm")
    reviewed = report["reviewed_labels"]
    lines = [
        "# Model card: practitioner-post topic classifier",
        "",
        f"_Generated by `signals model-card` from `reports/topic-eval.json` ({report['date']}). Don't edit by hand._",
        "",
        "## What it does",
        "",
        "Assigns one of five topics to a short English summary of a practitioner's post about coding agents, so new posts can be filed on the AI Engineer Log's community page without reading each one first.",
        "",
        "| Topic | Meaning |",
        "| --- | --- |",
        *[f"| `{k}` | {v} |" for k, v in TOPICS.items()],
        "",
        "## Data",
        "",
        f"- {report['posts']} posts from Threads, summarised in my own words (originals: {', '.join(f'{n} {l.upper()}' for l, n in report['languages'].items())}).",
        f"- Topic counts: {', '.join(f'{k} {v}' for k, v in report['topics'].items())}.",
        f"- Reference labels: {reviewed} of {report['posts']} reviewed by me; the rest are the labels assigned when the posts were curated with an agent's help."
        + (" Until more are reviewed, agreement with the reference is not the same as accuracy." if reviewed < report["posts"] else ""),
        "",
        "## Results",
        "",
        "| Method | Accuracy | Macro F1 |",
        "| --- | ---: | ---: |",
        f"| Majority class | {base['majority_class_accuracy']:.0%} | – |",
        _row("TF-IDF + logistic regression (CV)", base),
    ]
    if llm:
        lines.append(_row(f"LLM zero-shot ({llm['method'].split(' by ')[1].split(' via')[0]})", llm))
    lines += [
        "",
        f"- Baseline: {base['method']}.",
    ]
    if llm:
        cost = f"${llm['cost_usd']:.4f}" if llm.get("cost_usd") is not None else "unknown cost"
        lines += [
            f"- LLM: {llm['method']}; {cost} for the whole set.",
            f"- Posts where the LLM and the reference disagree ({len(llm['disagreements'])}): {', '.join(llm['disagreements']) or 'none'}. These are the first to review by hand.",
        ]
    lines += [
        "",
        "## Limits",
        "",
        "- The dataset is tiny, so one post moves accuracy by about three points. Treat differences under ten points as noise.",
        "- Topics overlap: a post about short instruction files to save tokens fits two topics. One label per post loses that.",
        "- Summaries are mine, not the original wording, so the classifier learns my phrasing as much as the authors'.",
        "",
        "## Retrain and validate",
        "",
        "```",
        "signals topics          # baseline, then LLM labels (cached), then report",
        "signals model-card      # regenerate this file",
        "```",
        "",
    ]
    return "\n".join(lines)


def write() -> None:
    report = json.loads(EVAL.read_text(encoding="utf-8"))
    CARD.write_text(render(report), encoding="utf-8")
