"""Aggregate session rows into the published report (JSON and Markdown)."""

from __future__ import annotations

from collections import Counter, defaultdict
from statistics import median

from .sessions import SessionStats


def processed_input(s: SessionStats) -> int:
    """All input the model read: uncached, cache reads and cache writes."""
    return s.input_tokens + s.cache_read_tokens + s.cache_write_tokens


def _share(part: float, whole: float) -> float | None:
    return round(part / whole, 3) if whole else None


def summarise(rows: list[SessionStats]) -> dict:
    by_agent: dict[str, list[SessionStats]] = defaultdict(list)
    for s in rows:
        by_agent[s.agent].append(s)

    agents = {}
    for agent, items in sorted(by_agent.items()):
        main = [s for s in items if s.kind == "main"]
        subs = [s for s in items if s.kind == "subagent"]
        processed = sum(processed_input(s) for s in items)
        prompts = sum(s.human_prompts for s in main)
        measured = [s for s in items if s.tool_errors is not None]
        tools = Counter()
        for s in items:
            tools.update(s.tools)
        agents[agent] = {
            "sessions": len(main),
            "subagent_transcripts": len(subs),
            "typed_prompts": prompts,
            "api_calls": sum(s.api_calls for s in items),
            "input_tokens_processed": processed,
            "output_tokens": sum(s.output_tokens for s in items),
            "cache_read_share": _share(sum(s.cache_read_tokens for s in items), processed),
            "subagent_token_share": _share(sum(processed_input(s) for s in subs), processed),
            "tokens_per_typed_prompt": round(processed / prompts) if prompts else None,
            "tool_calls": sum(s.tool_calls for s in items),
            "tool_error_rate": _share(sum(s.tool_errors for s in measured), sum(s.tool_calls for s in measured)) if measured else None,
            "compactions": sum(s.compactions for s in items),
            "median_session_minutes": median([s.minutes for s in main]) if main else None,
            "top_tools": dict(tools.most_common(8)),
        }

    projects = defaultdict(lambda: Counter())
    for s in rows:
        p = projects[s.project]
        p["sessions"] += s.kind == "main"
        p["input_tokens_processed"] += processed_input(s)
        p["output_tokens"] += s.output_tokens
        p["tool_calls"] += s.tool_calls

    dates = sorted(s.date for s in rows if s.date)
    return {
        "period": [dates[0], dates[-1]] if dates else None,
        "agents": agents,
        "projects": {k: dict(v) for k, v in sorted(projects.items(), key=lambda kv: -kv[1]["input_tokens_processed"])},
    }


SHARES = {"cache_read_share", "subagent_token_share", "tool_error_rate"}


def _n(value, key: str = "") -> str:
    if value is None:
        return "–"
    if key in SHARES:
        return f"{value:.0%}"
    return f"{value:,}" if isinstance(value, int) else str(value)


def markdown(summary: dict) -> str:
    period = summary["period"] or ["?", "?"]
    agents = summary["agents"]
    names = list(agents)
    rows = [
        ("Sessions", "sessions"),
        ("Sub-agent transcripts", "subagent_transcripts"),
        ("Typed prompts", "typed_prompts"),
        ("API calls", "api_calls"),
        ("Input tokens processed", "input_tokens_processed"),
        ("Output tokens", "output_tokens"),
        ("Input read from cache", "cache_read_share"),
        ("Input used by sub-agents", "subagent_token_share"),
        ("Input tokens per typed prompt", "tokens_per_typed_prompt"),
        ("Tool calls", "tool_calls"),
        ("Tool calls that failed", "tool_error_rate"),
        ("Compactions", "compactions"),
        ("Median session length (min)", "median_session_minutes"),
    ]
    out = [
        "# My coding-agent sessions",
        "",
        f"Personal projects only, {period[0]} to {period[1]}. Generated by `signals sessions`; numbers only, no prompts or code.",
        "",
        "| | " + " | ".join(names) + " |",
        "| --- | " + " | ".join("---:" for _ in names) + " |",
    ]
    out += [f"| {label} | " + " | ".join(_n(agents[a].get(key), key) for a in names) + " |" for label, key in rows]
    out += ["", "## By project", "", "| Project | Sessions | Input tokens processed | Output tokens | Tool calls |", "| --- | ---: | ---: | ---: | ---: |"]
    out += [f"| {p} | {v['sessions']} | {v['input_tokens_processed']:,} | {v['output_tokens']:,} | {v['tool_calls']:,} |" for p, v in summary["projects"].items()]
    out += ["", "## Most used tools", ""]
    for a in names:
        out.append(f"- **{a}**: " + ", ".join(f"{t} {n}" for t, n in agents[a]["top_tools"].items()))
    out += [
        "",
        "## Reading these numbers",
        "",
        "- Codex logs don't record tool failures, so its failure rate is blank. A Codex typed prompt is a started turn.",
        "- Input tokens per typed prompt is high because every API call re-reads the whole context, mostly from cache.",
        "- Codex reports cached input inside its input count; it is split out here so both agents use the same definitions.",
        "- Session length runs from the first to the last event and includes idle time.",
        "- The sample is small. These are descriptive numbers, not tests of any claim yet.",
        "",
    ]
    return "\n".join(out)
